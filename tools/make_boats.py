"""Placeholder boats (assets/items/rowboat.c, sailboat.c) and dock (assets/buildings/dock.c), in the
Item Editor's / Farm tab's exact formats (main.c BOATS + DOCKS).

The boats have only a held icon: with no Swing ("use") art the game draws each one's hull itself, sized
to its deck (boat_len x boat_wide tiles) with a wheel at the helm — main.c boat_hull_px(), ported in
hull() below for the preview.

    python tools/make_boats.py --preview out.png   the icons, the dock, and the hulls as the game draws them
    python tools/make_boats.py [--force]           writes the three files (--force: over existing ones)
"""
import json, math, os, sys
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
T = (0, 0, 0, 0)
TILE = 16
BOATS = [   # id, name, deck length, width, speed %, buy, sell, sail on the icon
    ('rowboat', 'Rowboat', 2, 1, 100, 2000, 500, False),
    ('sailboat', 'Sailboat', 4, 3, 170, 12000, 3000, True),
]


def pack(c):
    r, g, b, a = c
    if a < 128:
        return 0
    v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    return v or 0x0001


def arr(img):
    return [pack(img.getpixel((x, y))) for y in range(img.height) for x in range(img.width)]


def carray(px):
    return '\n'.join('    ' + ', '.join('0x%04x' % v for v in px[i:i + 12]) + ',' for i in range(0, len(px), 12))


def hull(length, wide, helm=0, direction='right'):
    """main.c boat_hull_px() for a deck of length x wide tiles, the bow pointing `direction`."""
    along_x = direction in ('left', 'right')
    w, h = (length * TILE, wide * TILE) if along_x else (wide * TILE, length * TILE)
    img = Image.new('RGBA', (w, h), T)
    ln, wd = (w, h) if along_x else (h, w)
    for y in range(h):
        for x in range(w):
            a, c = (x, y) if along_x else (y, x)
            if direction in ('left', 'up'):
                a = ln - 1 - a
            v, half = (c + 0.5) / wd * 2 - 1, 1.0
            taper = min(ln // 2, 22)
            if a >= ln - taper:
                t = (a + 0.5 - (ln - taper)) / taper
                half = math.sqrt(max(0.0, 1 - t * t))
            if abs(v) > half or (a < 2 and abs(v) > 0.8):
                continue
            ha, hc = helm * TILE + TILE / 2, (wide - 1) // 2 * TILE + TILE / 2
            da, dc = a + 0.5 - ha, c + 0.5 - hc
            r = math.hypot(da, dc)
            col = None
            if r < 6.2:
                col = (110, 70, 36) if r > 4.6 else (210, 170, 96) if r < 1.6 else (150, 100, 55) if abs(da) < 0.8 or abs(dc) < 0.8 else None
            if col is None:
                if abs(v) > half - 6.0 / wd or a < 3:
                    col = (176, 120, 66) if v < 0 else (92, 56, 30)
                else:
                    col = (118, 76, 42) if c % 4 == 0 else (150, 102, 58)
            img.putpixel((x, y), col + (255,))
    return img


def side_icon(sail):
    """16x16 side view for the bag."""
    f = Image.new('RGBA', (16, 16), T)
    dr = ImageDraw.Draw(f)
    if sail:
        dr.line([(8, 2), (8, 11)], fill=(110, 80, 50, 255))
        dr.polygon([(9, 2), (9, 10), (14, 10)], fill=(250, 250, 236, 255))
        dr.polygon([(7, 3), (7, 10), (3, 10)], fill=(236, 236, 220, 255))
        top, body, rim = (236, 240, 244), (60, 110, 170), (40, 70, 120)
    else:
        top, body, rim = (184, 132, 76), (132, 84, 46), (92, 56, 30)
        dr.line([(3, 6), (12, 12)], fill=(200, 170, 120, 255))
    dr.polygon([(1, 11), (14, 11), (12, 14), (3, 14)], fill=body + (255,))
    dr.line([(1, 11), (14, 11)], fill=top + (255,))
    dr.line([(3, 14), (12, 14)], fill=rim + (255,))
    return f


def item_c(id_, name, icon, attrs, notes):
    p = arr(icon)
    attr_lines = '\n'.join('    { "%s", %d },' % a for a in attrs)
    return f"""// AUTO-GENERATED by gameTools.html (Item Editor) — "{name}"
// Lives in assets/items/ as {id_}.c — the file name is the item id, keep it.
// Rebuild and it's in the game; maps drop it by the id "{id_}".
// {notes}
// Placeholder art (tools/make_boats.py): load your held icon, and the boat seen from above in the Swing tab.
#include "items.h"

static const uint16_t k_{id_}_passive_pixels[{len(p)}] = {{
{carray(p)}
}};


static const item_attr_t k_{id_}_attrs[] = {{
{attr_lines}
}};

const item_asset_t k_item_{id_} = {{
    .id = "{id_}",
    .display_name = "{name}",
    .max_stack = 1,
    .passive = {{ .w={icon.width}, .h={icon.height}, .frame_count=1, .interval_ms=150, .loop_count=-1, .pixels=k_{id_}_passive_pixels }},
    .use = {{ .frame_count = 0 }},
    .attrs = k_{id_}_attrs,
    .attr_count = {len(attrs)},
}};
"""


def dock_art():
    """48x48, all footprint: planks over the water, posts at the corners, the boat shop's post + sign bottom right."""
    f = Image.new('RGBA', (48, 48), T)
    dr = ImageDraw.Draw(f)
    plank, gap, edge = (156, 110, 66, 255), (104, 70, 40, 255), (84, 54, 30, 255)
    dr.rectangle([0, 0, 47, 47], fill=plank)
    for y in range(0, 48, 4):
        dr.line([(0, y), (47, y)], fill=gap)
    for y in range(0, 48, 8):
        for x in range((y // 4) % 2 * 8, 48, 16):
            dr.point((x, y + 2), fill=edge)
    dr.rectangle([0, 0, 47, 47], outline=edge)
    for (x, y) in [(1, 1), (43, 1), (1, 43)]:
        dr.rectangle([x, y, x + 3, y + 3], fill=(70, 46, 26, 255))
    dr.rectangle([36, 34, 43, 46], fill=(96, 62, 34, 255), outline=(52, 32, 18, 255))
    dr.rectangle([33, 33, 46, 40], fill=(226, 206, 160, 255), outline=(52, 32, 18, 255))
    dr.line([(36, 37), (43, 37)], fill=(60, 110, 170, 255))
    dr.line([(37, 38), (42, 38)], fill=(60, 110, 170, 255))
    return f


def fit_icon(img, mx=24):
    k = min(mx / img.width, mx / img.height, 1)
    return img.resize((max(1, round(img.width * k)), max(1, round(img.height * k))), Image.NEAREST)


def dock_c(art, icon, price):
    meta = {"name": "Dock", "footRows": 3, "doorCol": 2, "interior": "", "price": price, "w": art.width, "h": art.height,
            "iconW": icon.width, "iconH": icon.height, "iconAuto": True,
            "farm": {"kind": "dock", "capacity": 4, "animalDoor": -1, "hay": 240, "doorOpen": False, "doorShut": False}}
    px, ip = arr(art), arr(icon)
    return f"""// AUTO-GENERATED by gameTools.html (Buildings Editor) — "Dock"
// Lives in assets/buildings/ as dock.c — the file name is the building id, keep it.
// One building = what stands on the map below + the item "dock" that places it.
// {art.width}x{art.height} px, a {art.width // 16}x3-tile footprint; no inside.
// A dock: built out over the water from the shore, a deck to walk on; its post (column 2) is the boat shop.
// Everything here is const: it stays in flash (no RAM). RGB565, 0x0000 = see-through.
// BUILDINGS-EDITOR {json.dumps(meta, separators=(',', ':'))}
#include "items.h"
#include "buildings.h"

static const uint16_t k_building_dock_pixels[{len(px)}] = {{
{carray(px)}
}};

const building_def_t k_building_dock = {{
    .id = "dock",
    .w = {art.width},
    .h = {art.height},
    .foot_rows = 3,
    .door_col = 2,
    .interior = "",
    .pixels = k_building_dock_pixels,
    .houses = "",
    .capacity = 0,
    .animal_door = 0,   // 1 + the column the animals use (0 = none)
    .door_open = NULL,
    .hay_capacity = 0,
    .dock = true,
}};

// The item that puts it up: hold it and tap its hologram. The Build shop sells it for {price}.
static const uint16_t k_dock_icon_pixels[{len(ip)}] = {{
{carray(ip)}
}};
static const item_attr_t k_dock_attrs[] = {{
    {{ "buyable", {price} }},
}};
const item_asset_t k_item_dock = {{
    .id = "dock",
    .display_name = "Dock",
    .max_stack = 99,
    .passive = {{ .w={icon.width}, .h={icon.height}, .frame_count=1, .interval_ms=150, .loop_count=-1, .pixels=k_dock_icon_pixels }},
    .use = {{ .frame_count = 0 }},
    .attrs = k_dock_attrs,
    .attr_count = 1,
}};
"""


def main():
    dart = dock_art()
    files = {}
    for id_, name, ln, wd, speed, buy, sell, sail in BOATS:
        attrs = [('boat', 1), ('boat_len', ln), ('boat_wide', wd), ('boat_speed', speed), ('buyable', buy), ('sellable', sell)]
        note = (f'A boat: put in the water from a dock (for good), a {ln}x{wd}-tile deck to walk on, steered from the helm '
                f'at its stern; ponds, rivers and the sea at {speed}% of walking speed.')
        files[os.path.join(ROOT, 'assets', 'items', f'{id_}.c')] = item_c(id_, name, side_icon(sail), attrs, note)
    files[os.path.join(ROOT, 'assets', 'buildings', 'dock.c')] = dock_c(dart, fit_icon(dart), 2500)
    if '--preview' in sys.argv:
        out = sys.argv[sys.argv.index('--preview') + 1]
        sheet = Image.new('RGBA', (300, 120), (40, 90, 150, 255))
        x = 4
        for _, _, ln, wd, *_ in BOATS:
            for d in ('right', 'down'):
                hl = hull(ln, wd, 0, d)
                sheet.alpha_composite(hl, (x, 4))
                x += hl.width + 6
        sheet.alpha_composite(dart, (x, 4))
        for k, (*_, sail) in enumerate(BOATS):
            sheet.alpha_composite(side_icon(sail), (4 + k * 20, 100))
        sheet.resize((sheet.width * 3, sheet.height * 3), Image.NEAREST).save(out)
        print('preview', out)
        return
    for path, text in files.items():
        if os.path.exists(path) and '--force' not in sys.argv:
            print('exists, skipped (use --force):', path)
            continue
        with open(path, 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(text)
        print('wrote', path)


main()
